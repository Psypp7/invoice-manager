/**
 * Every piece of text on the M & P Windows screens, in English and Polish.
 *
 * "{name}" is filled in with a value. Entries written as functions
 * handle plurals, which work differently in the two languages.
 */

function enPlural(n, one, many) {
  return `${n} ${n === 1 ? one : many}`;
}

// Polish: 1 zlecenie, 2–4 zlecenia, 5+ zleceń (but 12–14 zleceń, 22 zlecenia).
function plPlural(n, one, few, many) {
  const lastDigit = n % 10;
  const lastTwo = n % 100;
  if (n === 1) return `${n} ${one}`;
  if (lastDigit >= 2 && lastDigit <= 4 && !(lastTwo >= 12 && lastTwo <= 14)) {
    return `${n} ${few}`;
  }
  return `${n} ${many}`;
}

